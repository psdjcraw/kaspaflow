#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dataDir = process.env.KASPAFLOW_DATA_DIR ?? path.join(process.cwd(), "data");
const outFile = process.argv[2] ?? path.join(process.cwd(), "db", "kaspaflow-import.sql");

const paymentsState = readJson("payments.json", { payments: [] });
const merchantSettings = readJson("merchant-settings.json", null);
const walletState = readJson("wallet-addresses.json", { addresses: [] });
const auditState = readJson("audit-events.json", { events: [] });
const expiryState = readJson("expiry-state.json", { expiredIds: [] });

const statements = [
  "-- Generated by scripts/export-postgres-sql.mjs",
  `-- Source data dir: ${dataDir}`,
  "begin;",
  "",
];

appendMerchantSettings(statements, merchantSettings);
appendWalletAddresses(statements, walletState.addresses ?? []);
appendPayments(statements, paymentsState.payments ?? [], expiryState.expiredIds ?? []);
appendAuditEvents(statements, auditState.events ?? []);

statements.push("commit;", "");

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, statements.join("\n"));
console.log(`Wrote ${outFile}`);

function appendMerchantSettings(lines, settings) {
  if (!settings) {
    return;
  }

  for (const store of settings.stores ?? []) {
    lines.push(
      `insert into merchant_stores (id, name, merchant_address, default_currency, active, updated_at) values (${values([
        store.id,
        store.name,
        store.merchantAddress,
        store.defaultCurrency,
        Boolean(store.active),
        settings.updatedAt ?? new Date().toISOString(),
      ])}) on conflict (id) do update set name = excluded.name, merchant_address = excluded.merchant_address, default_currency = excluded.default_currency, active = excluded.active, updated_at = excluded.updated_at;`,
    );
  }

  lines.push(
    `insert into merchant_settings (id, merchant_name, merchant_address, default_currency, active_store_id, updated_at) values (${values([
      "default",
      settings.merchantName,
      settings.merchantAddress,
      settings.defaultCurrency,
      settings.activeStoreId,
      settings.updatedAt ?? new Date().toISOString(),
    ])}) on conflict (id) do update set merchant_name = excluded.merchant_name, merchant_address = excluded.merchant_address, default_currency = excluded.default_currency, active_store_id = excluded.active_store_id, updated_at = excluded.updated_at;`,
  );

  for (const employee of settings.employees ?? []) {
    lines.push(
      `insert into merchant_employees (id, name, role, active, updated_at) values (${values([
        employee.id,
        employee.name,
        employee.role,
        Boolean(employee.active),
        settings.updatedAt ?? new Date().toISOString(),
      ])}) on conflict (id) do update set name = excluded.name, role = excluded.role, active = excluded.active, updated_at = excluded.updated_at;`,
    );
  }

  lines.push("");
}

function appendWalletAddresses(lines, addresses) {
  for (const address of addresses) {
    lines.push(
      `insert into wallet_addresses (id, label, address, store_id, network, active, created_at, updated_at) values (${values([
        address.id,
        address.label,
        address.address,
        address.storeId ?? null,
        address.network,
        Boolean(address.active),
        address.createdAt,
        address.createdAt,
      ])}) on conflict (id) do update set label = excluded.label, address = excluded.address, store_id = excluded.store_id, network = excluded.network, active = excluded.active, updated_at = excluded.updated_at;`,
    );
  }

  if (addresses.length) {
    lines.push("");
  }
}

function appendPayments(lines, payments, expiredIds) {
  const expired = new Set(expiredIds);

  for (const payment of payments) {
    const fiatAmount = payment.fiatAmount ?? payment.krwAmount ?? 0;
    const fiatCurrency = payment.fiatCurrency ?? "KRW";
    const rateFiatPerKas = payment.rateFiatPerKas ?? payment.rateKrwPerKas ?? 0;
    const simulated = payment.simulated ?? payment.txHash?.startsWith("simulated-") ?? false;

    lines.push(
      `insert into payments (id, merchant_name, merchant_address, fiat_amount, fiat_currency, rate_fiat_per_kas, kas_amount, status, tx_hash, received_kas_amount, simulated, created_at, expires_at, updated_at) values (${values([
        payment.id,
        payment.merchantName,
        payment.merchantAddress,
        fiatAmount,
        fiatCurrency,
        rateFiatPerKas,
        payment.kasAmount,
        payment.status,
        payment.txHash ?? null,
        payment.receivedKasAmount ?? null,
        simulated,
        payment.createdAt,
        payment.expiresAt,
        payment.createdAt,
      ])}) on conflict (id) do update set status = excluded.status, tx_hash = excluded.tx_hash, received_kas_amount = excluded.received_kas_amount, simulated = excluded.simulated, updated_at = excluded.updated_at;`,
    );

    const refund = payment.refund ?? { status: "none" };
    lines.push(
      `insert into payment_refunds (payment_id, status, customer_address, kas_amount, tx_hash, reason, note, requested_at, checked_at, confirmed_at, updated_at) values (${values([
        payment.id,
        refund.status ?? "none",
        refund.customerAddress ?? null,
        refund.kasAmount ?? null,
        refund.txHash ?? null,
        refund.reason ?? null,
        refund.note ?? null,
        refund.requestedAt ?? null,
        refund.checkedAt ?? null,
        refund.confirmedAt ?? null,
        refund.confirmedAt ?? refund.checkedAt ?? payment.createdAt,
      ])}) on conflict (payment_id) do update set status = excluded.status, customer_address = excluded.customer_address, kas_amount = excluded.kas_amount, tx_hash = excluded.tx_hash, reason = excluded.reason, note = excluded.note, requested_at = excluded.requested_at, checked_at = excluded.checked_at, confirmed_at = excluded.confirmed_at, updated_at = excluded.updated_at;`,
    );

    if (expired.has(payment.id)) {
      lines.push(
        `insert into expired_payments (payment_id) values (${sql(payment.id)}) on conflict (payment_id) do nothing;`,
      );
    }
  }

  if (payments.length) {
    lines.push("");
  }
}

function appendAuditEvents(lines, events) {
  for (const event of events) {
    lines.push(
      `insert into audit_events (id, type, message, payment_id, metadata, created_at) values (${values([
        event.id,
        event.type,
        event.message,
        event.paymentId ?? null,
        event.metadata ? jsonb(event.metadata) : null,
        event.createdAt,
      ])}) on conflict (id) do update set type = excluded.type, message = excluded.message, payment_id = excluded.payment_id, metadata = excluded.metadata, created_at = excluded.created_at;`,
    );
  }
}

function readJson(fileName, fallback) {
  const filePath = path.join(dataDir, fileName);

  if (!existsSync(filePath)) {
    return fallback;
  }

  return JSON.parse(readFileSync(filePath, "utf8"));
}

function values(entries) {
  return entries.map((entry) => entry?.__jsonb ? entry.value : sql(entry)).join(", ");
}

function jsonb(value) {
  return {
    __jsonb: true,
    value: `${sql(JSON.stringify(value))}::jsonb`,
  };
}

function sql(value) {
  if (value === null || value === undefined) {
    return "null";
  }

  if (typeof value === "number") {
    return Number.isFinite(value) ? String(value) : "null";
  }

  if (typeof value === "boolean") {
    return value ? "true" : "false";
  }

  return `'${String(value).replaceAll("'", "''")}'`;
}
